-- Calcula estatísticas num todo
-- Parâmetros: {resolution}
WITH
raw_data AS (
  SELECT
    *, CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS,
    hex(geoToH3(CG_LATITUDE_ATENDIMENTO, CG_LONGITUDE_ATENDIMENTO, {resolution})) AS CD_H3
  FROM
    BD_ANALYTICS_SIR.V_ATENDIMENTO_ACIONAMENTOS
),
groups AS (
  SELECT
    CD_H3,
    rd.NU_CNPJ AS NU_CNPJ,
    conc.NO_FANTASIA AS NO_FANTASIA,
    DS_TIPO_SERVICO,
    DS_TIPO_VEICULO_RECURSO,
    avgIf(CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS, CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS != 0) AS value,
    stddevPopStable(CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS) AS std_value,
    quantileExact(0.25)(CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS) AS q_25,
    quantileExact(0.50)(CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS) AS q_50,
    quantileExact(0.75)(CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS) AS q_75,
    minIf(CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS, CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS != 0) AS min_value,
    maxIf(CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS, CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS != 0) AS max_value,
    countIf(CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS != 0) AS QT_CONTAGEM
  FROM raw_data rd
  INNER JOIN BD_PER.TB_PARAMETROS_CONCESSIONARIAS conc
  ON rd.NU_CNPJ = conc.NU_CNPJ
  GROUP BY ALL
)
SELECT * FROM groups WHERE QT_CONTAGEM > 10