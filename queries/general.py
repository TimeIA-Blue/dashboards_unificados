AVAILABLE_COMPANIES_QUERY = """
SELECT * FROM
(
SELECT DISTINCT NU_CNPJ AS cnpj, 'Radar' AS dataset FROM BD_ANALYTICS_SIR.MV_RADAR_CONTAGEM_DIA
UNION ALL
SELECT DISTINCT NU_CNPJ AS cnpj, 'VIT' AS dataset FROM BD_ANALYTICS_SIR.MV_VIT_AVISTAMENTOS
UNION ALL
SELECT DISTINCT info.NU_CNPJ AS cnpj, 'SAT' AS dataset FROM BD_ANALYTICS_SIR.MV_SAT_CONTAGEM_DIA scd
INNER JOIN BD_ANALYTICS_SIR.V_SAT_INFO info
ON scd.CD_SEQ_SAT = info.CD_SEQ_SAT
UNION ALL
SELECT DISTINCT NU_CNPJ AS cnpj, 'Pedágio' AS dataset FROM BD_ANALYTICS_SIR.MV_PEDAGIO_CONTAGEM_DIARIA
UNION ALL
SELECT DISTINCT NU_CNPJ AS cnpj, 'Atendimento' AS dataset FROM BD_ANALYTICS_SIR.V_ATENDIMENTO_ACIONAMENTOS
)
"""

AVAILABLE_TIMESTAMPS_QUERY = """
SELECT
    DS_NOME_PARAMETRO,
    VL_VALOR
FROM BD_RAW_INTERNO.TB_PARAMETROS
WHERE DS_NOME_PARAMETRO = 'DT_DATA_INICIO'
ORDER BY CD_DEPLOY_ID DESCENDING LIMIT 1
UNION ALL
SELECT
    DS_NOME_PARAMETRO,
    VL_VALOR
FROM BD_RAW_INTERNO.TB_PARAMETROS
WHERE DS_NOME_PARAMETRO = 'DT_DATA_FIM'
ORDER BY CD_DEPLOY_ID DESCENDING
LIMIT 1
"""


@st.cache_data(ttl=21600)
def get_company_names():
    client = ch_client()
    company_names = (
        client.query_df("SELECT * FROM BD_PER.TB_PARAMETROS_CONCESSIONARIAS")
        .set_index("NU_CNPJ")
        .to_dict(orient="index")
    )
    company_names = {
        k: v["NO_FANTASIA"] for k, v in company_names.items() if k is not None
    }
    return company_names
