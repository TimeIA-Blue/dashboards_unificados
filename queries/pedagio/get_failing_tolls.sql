-- IN parameters: cnpj (string)
-- OUT fields: CD_PRACA_PEDAGIO (int), NO_PRACA_PEDAGIO (string), QT_CONTAGEM (int)
SELECT
    CD_PRACA_PEDAGIO,
    NO_PRACA_PEDAGIO,
    SUM(QT_CONTAGEM) AS QT_CONTAGEM
FROM BD_ANALYTICS_SIR.MV_PEDAGIO_CONTAGEM_DIARIA cd
INNER JOIN BD_ANALYTICS_SIR.V_PEDAGIO_INFO i
ON cd.CD_PRACA_PEDAGIO = i.CD_PRACA_PEDAGIO
WHERE NU_CNPJ = '{cnpj}'
GROUP BY CD_PRACA_PEDAGIO, NO_PRACA_PEDAGIO
HAVING QT_CONTAGEM < 1000