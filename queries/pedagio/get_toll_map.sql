-- IN parameters: cnpj (string)
-- OUT fields: CD_PRACA_PEDAGIO (int), NO_PRACA_PEDAGIO (string), CG_LATITUDE (float), CG_LONGITUDE(float), QT_CONTAGEM (int)
SELECT
    CD_PRACA_PEDAGIO,
    i.NO_PRACA_PEDAGIO AS NO_PRACA_PEDAGIO,
    i.CG_LATITUDE AS CG_LATITUDE,
    i.CG_LONGITUDE AS CG_LONGITUDE,
    SUM(QT_CONTAGEM) AS QT_CONTAGEM
FROM BD_ANALYTICS_SIR.MV_PEDAGIO_CONTAGEM_DIARIA cd
INNER JOIN BD_ANALYTICS_SIR.V_PEDAGIO_INFO i
ON cd.CD_PRACA_PEDAGIO = i.CD_PRACA_PEDAGIO
WHERE NU_CNPJ = '{cnpj}'
GROUP BY ALL