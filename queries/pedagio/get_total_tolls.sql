-- IN parameters: cnpj (string)
-- OUT fields: QT_TOTAL_PRACAS (int)
SELECT
    COUNT(DISTINCT CD_SEQ_PRACA_PEDAGIO) AS QT_TOTAL_PRACAS
FROM BD_RAW_SIR_ORIGEM.TB_PRACA_PEDAGIO
WHERE CD_CONCESSIONARIA = (SELECT DISTINCT CD_SEQ_CONCESSIONARIA FROM BD_RAW_SIR_ORIGEM.TB_CONCESSIONARIA WHERE NU_CNPJ = '{cnpj}');