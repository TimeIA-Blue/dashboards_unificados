-- IN parameters: none
-- OUT fields: NU_CNPJ, CD_PONTO, CG_LATITUDE, CG_LONGITUDE, DS_TIPO_PONTO
SELECT
    NU_CNPJ,
    CD_PRACA_PEDAGIO AS CD_PONTO,
    CG_LATITUDE,
    CG_LONGITUDE,
    'Pedágio' AS DS_TIPO_PONTO
FROM BD_ANALYTICS_SIR.V_PEDAGIO_INFO
UNION ALL
SELECT
    NU_CNPJ,
    CD_RADAR AS CD_PONTO,
    CG_LATITUDE,
    CG_LONGITUDE,
    'Radar' AS DS_TIPO_PONTO
FROM BD_ANALYTICS_SIR.V_RADAR_INFO
