-- IN parameters: date_start (string#date), date_end (string#date)
-- OUT fields: NU_CNPJ, DS_PLACA, DT_INSTANTE_ANTERIOR, VL_DELTA, VL_DISTANCIA_KM
SELECT
    NU_CNPJ,
    DS_PLACA,
    DT_INSTANTE_ANTERIOR,
    VL_DELTA,
    VL_DISTANCIA_KM
FROM (
    SELECT
        NU_CNPJ,
        DS_PLACA,
        DT_PASSAGEM_ANTERIOR AS DT_INSTANTE_ANTERIOR,
        (VL_INTERVALO * 60)::Int64 AS VL_DELTA,
        CD_RODOVIA_PONTO_ANTERIOR,
        CD_RODOVIA_PONTO,
        VL_DISTANCIA_KM
    FROM BD_ANALYTICS_SIR.MV_VIT_INTERVALOS_VEICULOS
    WHERE DT_PASSAGEM BETWEEN toDate('{date_start}') AND toDate('{date_end}')
)
WHERE
    VL_DELTA != 0
    AND VL_DISTANCIA_KM != 0
    AND CD_RODOVIA_PONTO_ANTERIOR = CD_RODOVIA_PONTO
