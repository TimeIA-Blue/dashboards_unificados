-- Padrão SQL para obter os dados brutos com tempo zero em uma lista de hexágonos.
WITH raw AS (
  SELECT
    *,
    CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS,
    geoDistance(CG_LONGITUDE_OCORRENCIA, CG_LATITUDE_OCORRENCIA, CG_LONGITUDE_ATENDIMENTO, CG_LATITUDE_ATENDIMENTO) AS dist,
    hex(geoToH3(CG_LATITUDE_ATENDIMENTO, CG_LONGITUDE_ATENDIMENTO, {resolution})) AS h3,
    (CALC_DELTA_ACIONAMENTO_CHEGADA_MINUTOS < 1) AS rapido,
    (dist < 1000) AS proximo
  FROM BD_ANALYTICS_SIR.V_ATENDIMENTO_ACIONAMENTOS
), groups AS (
  SELECT
    h3,
    raw.NU_CNPJ AS NU_CNPJ,
    conc.NO_FANTASIA AS NO_FANTASIA,
    DS_TIPO_SERVICO,
    DS_TIPO_VEICULO_RECURSO,
    COUNT(*) AS COUNT_TOTAL,
    countIf(rapido AND proximo) AS COUNT_ZERO_AUTOACIONADO,
    countIf(rapido AND NOT proximo) AS COUNT_ZERO,
    (COUNT_ZERO_AUTOACIONADO / COUNT_TOTAL) AS PCT_AUTOACIONADO,
    (COUNT_ZERO / COUNT_TOTAL) AS PCT_ZERO
  FROM raw
  INNER JOIN BD_PER.TB_PARAMETROS_CONCESSIONARIAS conc
  ON raw.NU_CNPJ = conc.NU_CNPJ
  GROUP BY ALL
)
SELECT * FROM groups WHERE COUNT_TOTAL > 10